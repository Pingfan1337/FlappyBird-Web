// Generates js/atlas.js from the original atlas.txt (name w h u v uw vh).
import fs from 'fs';
const rows = fs.readFileSync(new URL('./atlas.txt', import.meta.url), 'utf8').trim().split(/\r?\n/).map(l => l.trim().split(/\s+/));
const names = rows.map(r => r[0]);
const rects = rows.flatMap(r => [Math.round(+r[3] * 1024), Math.round(+r[4] * 1024), +r[1], +r[2]]);
const out = `// Generated by tools/gen-atlas.mjs from the original atlas.txt. Do not edit.
// Pixel rectangles (x, y, w, h) inside the 1024x1024 atlas, indexed by sprite id.
export const NAMES = ${JSON.stringify(names)};
export const RECT = new Int16Array(${JSON.stringify(rects)});
export const SPR = Object.freeze(Object.fromEntries(NAMES.map((n, i) => [n, i])));
`;
fs.writeFileSync(new URL('../js/atlas.js', import.meta.url), out);
console.log(names.length, 'sprites');
